import { spawn } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { arch, release, type } from 'node:os';
import { dirname, join, resolve } from 'node:path';

const projectRoot = resolve(process.argv[2] || process.cwd());
const sdkRoot = resolveSdkRoot();
const studioHome = resolveStudioHome(sdkRoot);
const hvigor = join(studioHome, 'tools', 'hvigor', 'bin', 'hvigorw');
const timeoutMs = positiveInteger(process.env.HOST_TEST_TIMEOUT_MS, 60_000);
const modules = ['entry', 'phone'];

requireFile(hvigor, 'Hvigor wrapper');

const startedAt = Date.now();
const summaries = [];
for (const moduleName of modules) {
  summaries.push(await runModuleTests(moduleName));
}

const totalTests = summaries.reduce((sum, summary) => sum + summary.tests, 0);
const totalPass = summaries.reduce((sum, summary) => sum + summary.pass, 0);
const elapsedMs = Date.now() - startedAt;
process.stdout.write(
  `Host tests: PASS (${totalPass}/${totalTests}, ${type()} ${release()} ${arch()}, ${elapsedMs} ms)\n`
);

async function runModuleTests(moduleName) {
  const reportPath = join(projectRoot, moduleName, '.test', 'default', 'intermediates',
    'test', 'coverage_data', 'test_result.txt');
  const reportMtimeBefore = existsSync(reportPath) ? statSync(reportPath).mtimeMs : -1;
  const expectedTests = countSourceTests(join(projectRoot, moduleName, 'src', 'test'));
  if (expectedTests === 0) {
    fail(`No source tests found for ${moduleName}.`);
  }

  const moduleStartedAt = Date.now();
  const args = [
    '--mode', 'module',
    '-p', 'product=default',
    '-p', `module=${moduleName}@default`,
    '-p', 'buildMode=debug',
    'test', '--no-daemon'
  ];
  const status = await spawnWithTimeout(hvigor, args, moduleName);
  if (status !== 0) {
    fail(`${moduleName} host tests exited with status ${status}.`);
  }
  requireFile(reportPath, `${moduleName} Hypium text report`);

  const reportStat = statSync(reportPath);
  if (reportStat.mtimeMs <= reportMtimeBefore || reportStat.mtimeMs < moduleStartedAt - 1_000) {
    fail(`${moduleName} Hypium report was not regenerated by the current run: ${reportPath}`);
  }
  const summary = parseSummary(readFileSync(reportPath, 'utf8'), moduleName);
  if (summary.tests !== expectedTests) {
    fail(`${moduleName} report contains ${summary.tests} tests but source contains ${expectedTests}.`);
  }
  if (summary.failure !== 0 || summary.error !== 0 || summary.ignore !== 0 ||
    summary.pass !== summary.tests) {
    fail(`${moduleName} Hypium report failed: ${summary.pass}/${summary.tests} passed, ` +
      `${summary.failure} failure, ${summary.error} error, ${summary.ignore} ignored.`);
  }

  const elapsedMs = Date.now() - moduleStartedAt;
  process.stdout.write(`${moduleName}: PASS (${summary.pass}/${summary.tests}, ${elapsedMs} ms, ${reportPath})\n`);
  return summary;
}

function spawnWithTimeout(command, args, moduleName) {
  return new Promise((resolvePromise, rejectPromise) => {
    const nodeBin = dirname(process.execPath);
    const currentPath = process.env.PATH || '/usr/bin:/bin:/usr/sbin:/sbin';
    const child = spawn(command, args, {
      cwd: projectRoot,
      env: {
        ...process.env,
        PATH: `${nodeBin}:${currentPath}`,
        DEVECO_SDK_HOME: sdkRoot
      },
      stdio: 'inherit'
    });
    let timedOut = false;
    const timer = setTimeout(() => {
      timedOut = true;
      child.kill('SIGTERM');
      setTimeout(() => child.kill('SIGKILL'), 2_000).unref();
    }, timeoutMs);

    child.on('error', (error) => {
      clearTimeout(timer);
      rejectPromise(error);
    });
    child.on('exit', (code, signal) => {
      clearTimeout(timer);
      if (timedOut) {
        fail(`${moduleName} host tests timed out after ${timeoutMs} ms. On Darwin, run this gate ` +
          'in an environment that permits the Hypium runner to open its local socket.');
      }
      if (signal !== null) {
        fail(`${moduleName} host tests ended from signal ${signal}.`);
      }
      resolvePromise(code ?? 1);
    });
  });
}

function parseSummary(report, moduleName) {
  const match = report.match(
    /Tests run:\s*(\d+), Failure:\s*(\d+), Error:\s*(\d+), Pass:\s*(\d+), Ignore:\s*(\d+)/
  );
  if (match === null) {
    fail(`Cannot parse ${moduleName} Hypium summary.`);
  }
  return {
    tests: Number(match[1]),
    failure: Number(match[2]),
    error: Number(match[3]),
    pass: Number(match[4]),
    ignore: Number(match[5])
  };
}

function countSourceTests(directory) {
  let count = 0;
  for (const path of listFiles(directory)) {
    if (!path.endsWith('.test.ets')) {
      continue;
    }
    const source = readFileSync(path, 'utf8');
    count += (source.match(/\bit\s*\(/g) || []).length;
  }
  return count;
}

function listFiles(directory) {
  if (!existsSync(directory)) {
    return [];
  }
  const paths = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      paths.push(...listFiles(path));
    } else if (entry.isFile()) {
      paths.push(path);
    }
  }
  return paths;
}

function resolveSdkRoot() {
  if (process.env.DEVECO_SDK_HOME) {
    return resolve(process.env.DEVECO_SDK_HOME);
  }
  if (process.env.DEVECO_STUDIO_HOME) {
    return join(resolve(process.env.DEVECO_STUDIO_HOME), 'sdk');
  }
  return '/Applications/DevEco-Studio.app/Contents/sdk';
}

function resolveStudioHome(resolvedSdkRoot) {
  if (process.env.DEVECO_STUDIO_HOME) {
    return resolve(process.env.DEVECO_STUDIO_HOME);
  }
  return dirname(resolvedSdkRoot);
}

function positiveInteger(value, fallback) {
  const parsed = Number(value);
  return Number.isInteger(parsed) && parsed > 0 ? parsed : fallback;
}

function requireFile(path, label) {
  if (!existsSync(path)) {
    fail(`Cannot find ${label}: ${path}`);
  }
}

function fail(message) {
  throw new Error(message);
}
