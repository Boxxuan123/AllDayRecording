import { execFileSync } from 'node:child_process';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(process.argv[2] ?? fileURLToPath(new URL('../..', import.meta.url)));
const text = readFileSync(resolve(root, 'AppScope/app.json5'), 'utf8');
const value = (key) => JSON.parse(text.match(new RegExp('"' + key + '"\\s*:\\s*("[^"]*"|[0-9]+)'))[1]);
const git = (...args) => execFileSync('git', ['-C', root, ...args], { encoding: 'utf8', timeout: 5000 }).trim();
const info = { release_version: value('versionName'), version_code: value('versionCode'),
  build_version: value('buildVersion'), git_commit: git('rev-parse', 'HEAD'),
  built_at: new Date().toISOString(), dirty: git('status', '--porcelain', '--untracked-files=normal').length > 0 };
const out = resolve(root, 'common/src/main/ets/diagnostics/GeneratedBuildIdentity.ets');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, '// Generated by Hvigor. Do not edit or commit.\n' +
  Object.entries(info).map(([key, val]) => 'export const BUILD_' + key.toUpperCase() +
    ': ' + typeof val + ' = ' + JSON.stringify(val) + ';').join('\n') + '\n');
console.log('[build] ' + JSON.stringify(info));
